// npm run build:astro → astro-embed/, a drop-in for an Astro site (PLAN.md §8 P8):
//   astro-embed/public/double-story/        double-story.js (+ lazy chunks/), double-story.css, fonts.css, fonts/
//   astro-embed/src/components/DoubleStory.astro   server-rendered markup + the tags that load the files above
// Copy both folders into the Astro project and render <DoubleStory />. No npm packages needed there.
import { build, createServer, type InlineConfig, type Plugin } from 'vite';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

// Vite's dev server (used below to render the markup) flips NODE_ENV to development: pin production
// first and build before starting it, so import.meta.env.DEV blocks are compiled out.
process.env.NODE_ENV = 'production';
const root = resolve(import.meta.dirname, '..');
const OUT = join(root, 'astro-embed');
const PUBLIC = join(OUT, 'public', 'double-story');
const COMPONENT = join(OUT, 'src', 'components', 'DoubleStory.astro');

/** The demo page puts brand tokens on :root; on the host site they stay inside the section. */
const scopeTokens = (): Plugin => ({
  name: 'double-scope-tokens',
  enforce: 'pre',
  transform(code, id) {
    if (!id.split('?')[0].endsWith('/src/styles/tokens.css')) return;
    const out = code.replace('#double-story, :root {', '#double-story {');
    if (out === code) throw new Error('tokens.css selector changed: update scopeTokens() in scripts/build-astro.ts');
    return out;
  },
});

const config = (entry: string, name: string, css: string, emptyOutDir: boolean): InlineConfig => ({
  root,
  configFile: false,
  mode: 'production',
  logLevel: 'warn',
  base: './', // chunk and font URLs resolve relative to the file that references them
  define: { __DOUBLE_DEBUG__: 'false' },
  plugins: [scopeTokens()],
  build: {
    outDir: PUBLIC,
    emptyOutDir,
    copyPublicDir: false,
    target: 'es2022',
    modulePreload: false,
    cssCodeSplit: false,
    rollupOptions: {
      input: { [name]: join(root, entry) },
      preserveEntrySignatures: 'exports-only', // keep mount() / mountAll() importable
      output: {
        entryFileNames: '[name].js',
        chunkFileNames: 'chunks/[name]-[hash].js',
        assetFileNames: (a) => ((a.names?.[0] ?? '').endsWith('.css') ? css : 'fonts/[name]-[hash][extname]'),
      },
    },
  },
});

// 1 · the story (JS + scoped CSS), then the optional brand fonts
await build(config('src/embed.ts', 'double-story', 'double-story.css', true));
await build(config('src/fonts.ts', 'fonts', 'fonts.css', false));
rmSync(join(PUBLIC, 'fonts.js'), { force: true }); // CSS-only entry: its JS stub is empty

// 2 · static markup, rendered from content.ts by the same code the demo page uses
const server = await createServer({
  root, configFile: false, logLevel: 'warn', appType: 'custom',
  server: { middlewareMode: true, hmr: false, ws: false },
});
const { storyMarkup } = (await server.ssrLoadModule('/src/markup.ts')) as typeof import('../src/markup.ts');
const markup = storyMarkup();
await server.close();

const v = (file: string) => createHash('sha256').update(readFileSync(join(PUBLIC, file))).digest('hex').slice(0, 10);
const versions = { js: v('double-story.js'), css: v('double-story.css'), fonts: v('fonts.css') };

// 3 · the Astro component
mkdirSync(join(OUT, 'src', 'components'), { recursive: true });
writeFileSync(COMPONENT, `---
/**
 * The Double · exploded-view scroll story.
 * Generated by \`npm run build:astro\` in the double-story repo from src/content.ts: edit the copy there
 * and rebuild rather than editing this file.
 *
 *   <DoubleStory />                        brand fonts bundled, smooth scroll on
 *   <DoubleStory fonts={false} />          the page already loads Funnel Display, Geist, Geist Mono, Newsreader
 *   <DoubleStory smoothScroll={false} />   the page already runs Lenis (or another smooth scroller)
 *
 * Needs public/double-story/ (shipped next to this file). Works with Astro view transitions.
 */
interface Props {
  /** Load the bundled brand fonts. Default true; pass false where the page already has them. */
  fonts?: boolean;
  /** Lenis smooth scrolling while the story runs. Default true. */
  smoothScroll?: boolean;
  /** URL the public/double-story/ folder is served from. Default: <site base>/double-story. */
  assets?: string;
}
const {
  fonts = true,
  smoothScroll = true,
  assets = \`\${import.meta.env.BASE_URL.replace(/\\/$/, '')}/double-story\`,
} = Astro.props;
const V = ${JSON.stringify(versions)};
const MARKUP = ${JSON.stringify(markup)};
const html = smoothScroll ? MARKUP : MARKUP.replace('<section id="double-story"', '<section id="double-story" data-smooth-scroll="false"');
---
{fonts && <link rel="stylesheet" href={\`\${assets}/fonts.css?v=\${V.fonts}\`} />}
<link rel="stylesheet" href={\`\${assets}/double-story.css?v=\${V.css}\`} />
<Fragment set:html={html} />
<script is:inline type="module" src={\`\${assets}/double-story.js?v=\${V.js}\`}></script>
`);

console.log(`astro-embed/ ready  (js ${versions.js} · css ${versions.css} · fonts ${versions.fonts})`);
