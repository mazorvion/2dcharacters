// Copies the SVG paths we need from simple-icons + lucide-static into src/overlay/icons.ts.
// Run: npm run icons
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const si = (slug: string) => resolve(root, 'node_modules/simple-icons/icons', `${slug}.svg`);
const lu = (name: string) => resolve(root, 'node_modules/lucide-static/icons', `${name}.svg`);
const siData: { slug: string; hex: string; title: string }[] =
  JSON.parse(readFileSync(resolve(root, 'node_modules/simple-icons/data/simple-icons.json'), 'utf8'));

const BRANDS = ['whatsapp', 'gmail', 'googlemeet', 'slack', 'instagram', 'hubspot', 'salesforce', 'zoho',
  'googlesheets', 'googlecalendar', 'calendly', 'youtube', 'linkedin', 'x', 'substack', 'googledrive',
  'notion', 'googledocs', 'zapier', 'stripe'];
// Removed from simple-icons at the brand's request: fall back to a neutral monogram tile.
const MONOGRAM: Record<string, { text: string; hex: string; title: string }> = {
  slack: { text: 'S', hex: '4A154B', title: 'Slack' },
  salesforce: { text: 'sf', hex: '00A1E0', title: 'Salesforce' },
  linkedin: { text: 'in', hex: '0A66C2', title: 'LinkedIn' },
};
const GLYPHS = ['globe', 'phone', 'file-text', 'link', 'plug', 'shield', 'lock', 'code', 'presentation', 'mail', 'id-card', 'layout-template',
  'mic', 'audio-lines', 'brain', 'sparkles', 'message-circle', 'ear', 'book-open', 'lightbulb', 'calendar-check', 'check'];

interface Icon { title: string; color: string; svg: string }
const out: Record<string, Icon> = {};

for (const slug of BRANDS) {
  if (existsSync(si(slug))) {
    const raw = readFileSync(si(slug), 'utf8');
    const d = raw.match(/<path d="([^"]+)"/)![1];
    const meta = siData.find((i) => i.slug === slug)!;
    out[slug] = { title: meta.title, color: `#${meta.hex}`,
      svg: `<svg viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg" fill="currentColor"><path d="${d}"/></svg>` };
  } else if (MONOGRAM[slug]) {
    const m = MONOGRAM[slug];
    const size = m.text.length > 1 ? 11 : 15;
    out[slug] = { title: m.title, color: `#${m.hex}`,
      svg: `<svg viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg"><rect x="1" y="1" width="22" height="22" rx="5" fill="currentColor"/><text x="12" y="12.5" fill="#fff" font-family="Arial,sans-serif" font-weight="700" font-size="${size}" text-anchor="middle" dominant-baseline="central">${m.text}</text></svg>` };
  } else throw new Error(`missing brand icon ${slug}`);
}

for (const name of GLYPHS) {
  const raw = readFileSync(lu(name), 'utf8').replace(/<!--.*?-->/s, '');
  const inner = raw.slice(raw.indexOf('>', raw.indexOf('<svg')) + 1, raw.lastIndexOf('</svg>'))
    .replace(/\s*\n\s*/g, '');
  out[name] = { title: name, color: '#15172b',
    svg: `<svg viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>` };
}

const body = `// GENERATED by scripts/build-icons.ts — do not edit.
// Brand paths: simple-icons (CC0; marks are trademarks of their owners). Glyphs: lucide-static (ISC).
export interface Icon { title: string; color: string; svg: string }
export const ICONS: Record<string, Icon> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(resolve(root, 'src/overlay/icons.ts'), body);
console.log(`icons.ts: ${Object.keys(out).length} icons`);
